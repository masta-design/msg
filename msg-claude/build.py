def crumbs(items):
    # текущую страницу не показываем; на мобильных CSS оставляет только предыдущий раздел
    out = ['<a href="%s">%s</a>' % (href, t) for t, href in items[:-1]]
    return '<nav class="wrap crumbs" aria-label="Хлебные крошки">%s</nav>' % '<span>/</span>'.join(out)


