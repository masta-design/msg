def page_div(name, title, active, cr, fn, hidden=False):
    return B.no_dot('<div class="page" data-page="%s" data-title="%s — МСГ, прототип"%s>%s%s<main>%s</main>%s</div>'
                    % (name, title, ' hidden' if hidden else '', header(active), cr(), fn(), footer()))


def build():
    here = os.path.dirname(os.path.abspath(__file__))
    css = open(os.path.join(here, 'styles.css'), encoding='utf-8').read()
    js = open(os.path.join(here, 'app.js'), encoding='utf-8').read()
    out = os.path.join(here, 'dist')
    if os.path.exists(out):
        shutil.rmtree(out)
    multi = os.path.join(out, 'msg-prototype')
    os.makedirs(os.path.join(multi, 'assets'))

    # ---- многостраничная версия
    B.CFG['mode'] = 'multi'
    for name, title, active, cr, fn in PAGES:
        html = ('<!doctype html><html lang="ru"><head>%s<title>%s — МСГ, прототип</title>%s<link rel="stylesheet" href="assets/styles.css"></head>'
                '<body>%s%s<script charset="utf-8" src="assets/app.js"></script></body></html>'
                % (HEAD, title, FONT, page_div(name, title, active, cr, fn), B.no_dot(modal_html())))
        open(os.path.join(multi, name + '.html'), 'w', encoding='utf-8').write(html)
    open(os.path.join(multi, 'index.html'), 'w', encoding='utf-8').write(
        '<!doctype html><html lang="ru"><head><meta charset="utf-8"><meta http-equiv="refresh" content="0; url=services.html"><title>МСГ, прототип</title></head>'
        '<body><a href="services.html">Открыть прототип</a></body></html>')
    open(os.path.join(multi, 'assets', 'styles.css'), 'w', encoding='utf-8').write(css)
    open(os.path.join(multi, 'assets', 'app.js'), 'w', encoding='utf-8').write(js)
    zp = os.path.join(out, 'msg-prototype.zip')
    with zipfile.ZipFile(zp, 'w', zipfile.ZIP_DEFLATED) as z:
        for root, _, files in os.walk(multi):
            for f in files:
                p = os.path.join(root, f)
                z.write(p, os.path.relpath(p, out))

    # ---- одностраничная версия (для публикации)
    B.CFG['mode'] = 'spa'
    body = ''.join(page_div(n, t, a, c, f, hidden=(n != 'services')) for n, t, a, c, f in PAGES)
    html = ('<!doctype html><html lang="ru"><head>%s<title>Все сервисы — МСГ, прототип</title>%s<style>%s</style></head>'
            '<body>%s%s<script>%s</script></body></html>' % (HEAD, FONT, css, body, B.no_dot(modal_html()), js))
    open(os.path.join(out, 'msg-prototype.html'), 'w', encoding='utf-8').write(html)
    print('ok', len(html) // 1024, 'KB')


if __name__ == '__main__':
    build()
